/* =========================================================
   EVENTS
========================================================= */

function initEvents() {

  const navbar =
    document.getElementById("navbar");

  if (navbar) {

    const updateNavbar = () => {

      navbar.classList.toggle(
        "scrolled",
        window.scrollY > 50
      );

    };

    updateNavbar();

    window.addEventListener(
      "scroll",
      updateNavbar,
      {
        passive: true
      }
    );

  }


  /* Smooth Scroll */

  document
    .querySelectorAll("[data-scroll]")
    .forEach(button => {

      button.addEventListener(
        "click",
        event => {

          event.preventDefault();

          const target =
            document.querySelector(
              button.dataset.scroll
            );

          if (target) {

            target.scrollIntoView({
              behavior: "smooth",
              block: "start"
            });

          }

          closeMobileMenu();

        }
      );

    });


  /* Navigation */

  document
    .querySelectorAll(
      "#nav-links a, #mobile-links a"
    )
    .forEach(link => {

      link.addEventListener(
        "click",
        () => {

          closeMobileMenu();

        }
      );

    });


  /* Mobile Menu */

  const menuOpen =
    document.getElementById("menu-open");

  const menuClose =
    document.getElementById("menu-close");


  if (menuOpen) {

    menuOpen.addEventListener(
      "click",
      openMobileMenu
    );

  }


  if (menuClose) {

    menuClose.addEventListener(
      "click",
      closeMobileMenu
    );

  }


  /* Modal */

  setupModal();


  /* Audit */

  const auditBtn =
    document.getElementById("audit-btn");

  if (auditBtn) {

    auditBtn.addEventListener(
      "click",
      () => {

        showToast(
          "Audit request received — connect your form/email here."
        );

      }
    );

  }

}

/* =========================================================
   MOBILE MENU
========================================================= */

function openMobileMenu() {

  const menu =
    document.getElementById(
      "mobile-menu"
    );

  const trigger =
    document.getElementById(
      "menu-open"
    );


  if (!menu) return;


  menu.classList.add(
    "open"
  );

  menu.setAttribute(
    "aria-hidden",
    "false"
  );


  if (trigger) {

    trigger.setAttribute(
      "aria-expanded",
      "true"
    );

  }

  document.body.classList.add(
    "modal-open"
  );

}


function closeMobileMenu() {

  const menu =
    document.getElementById(
      "mobile-menu"
    );

  const trigger =
    document.getElementById(
      "menu-open"
    );


  if (!menu) return;


  menu.classList.remove(
    "open"
  );

  menu.setAttribute(
    "aria-hidden",
    "true"
  );


  if (trigger) {

    trigger.setAttribute(
      "aria-expanded",
      "false"
    );

  }

  document.body.classList.remove(
    "modal-open"
  );

}

/* =========================================================
   REEL MODAL
========================================================= */

function setupModal() {

  const modal =
    document.getElementById("modal");

  const watchReel =
    document.getElementById("watch-reel");

  const modalClose =
    document.getElementById("modal-close");


  if (!modal) return;


  const openModal = () => {

    modal.classList.add(
      "open"
    );

    modal.setAttribute(
      "aria-hidden",
      "false"
    );

    document.body.classList.add(
      "modal-open"
    );

  };


  const closeModal = () => {

    modal.classList.remove(
      "open"
    );

    modal.setAttribute(
      "aria-hidden",
      "true"
    );

    document.body.classList.remove(
      "modal-open"
    );

  };


  if (watchReel) {

    watchReel.addEventListener(
      "click",
      openModal
    );

  }


  if (modalClose) {

    modalClose.addEventListener(
      "click",
      closeModal
    );

  }


  modal.addEventListener(
    "click",
    event => {

      if (
        event.target === modal
      ) {

        closeModal();

      }

    }
  );


  document.addEventListener(
    "keydown",
    event => {

      if (
        event.key === "Escape"
      ) {

        closeModal();

      }

    }
  );

}

/* =========================================================
   TESTIMONIAL
========================================================= */

function renderTestimonial(index) {

  const testimonial =
    testimonials[index];

  if (!testimonial) return;


  const avatar =
    document.getElementById(
      "testimonial-avatar"
    );

  const stars =
    document.getElementById(
      "testimonial-stars"
    );

  const text =
    document.getElementById(
      "testimonial-text"
    );

  const name =
    document.getElementById(
      "testimonial-name"
    );

  const role =
    document.getElementById(
      "testimonial-role"
    );

  const dots =
    document.getElementById(
      "testimonial-dots"
    );


  if (
    !avatar ||
    !stars ||
    !text ||
    !name ||
    !role ||
    !dots
  ) {

    return;

  }


  avatar.innerHTML = `
    <img
      src="${testimonial.img}"
      alt="${testimonial.name}"
    >
  `;


  stars.innerHTML =
    Array.from(
      {
        length:
          testimonial.rating
      },
      () => `
        <i data-lucide="star"></i>
      `
    ).join("");


  text.textContent =
    `"${testimonial.text}"`;


  name.textContent =
    testimonial.name;


  role.textContent =
    testimonial.role;


  dots.innerHTML =
    testimonials
      .map(
        (_, i) => `
          <button
            type="button"
            class="dot ${i === index ? "active" : ""}"
            aria-label="Testimonial ${i + 1}"
            aria-pressed="${i === index}"
          ></button>
        `
      )
      .join("");


  dots
    .querySelectorAll(".dot")
    .forEach(
      (dot, i) => {

        dot.addEventListener(
          "click",
          () => {

            renderTestimonial(i);

          }
        );

      }
    );


  refreshIcons();

}

/* =========================================================
   LUCIDE ICONS
========================================================= */

function refreshIcons() {

  if (
    typeof lucide !== "undefined"
  ) {

    lucide.createIcons();

  }

}

/* =========================================================
   TOAST
========================================================= */

function showToast(message) {

  const toast =
    document.getElementById(
      "toast"
    );


  if (!toast) return;


  toast.textContent =
    message;


  toast.classList.add(
    "show"
  );


  setTimeout(
    () => {

      toast.classList.remove(
        "show"
      );

    },
    2800
  );

}